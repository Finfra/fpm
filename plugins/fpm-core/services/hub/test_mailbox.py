#!/usr/bin/env python3
# test_mailbox.py — Issue353_2 M2-a/M2-b 회귀 테스트
#
# ⚠️ 글로벌 SCAR 아님 (___pm 프로젝트 소유). transcript tail → 메일박스 적재와
#   pull 프로토콜(304/205/증분)을 검증한다.
